// One-off generator: scans public/beyblade-parts/{bx,cx,ux}/** and writes
// lib/beybladeParts.generated.ts with typed part lists per generation/category.
import { readdirSync, writeFileSync } from "fs";
import { join } from "path";

const ROOT = join(process.cwd(), "public", "beyblade-parts");
const OUT = join(process.cwd(), "lib", "beybladeParts.generated.ts");

const PREFIXES = {
  Blades: ["RatchetBlade", "Blade"],
  Bits: ["Bit"],
  Ratchets: ["Ratchet"],
  MainBlades: ["MainBlade"],
  LockChips: ["LockChip"],
  AssistBlades: ["AssistBlade"],
  OverBlades: ["OverBlade"],
  MetalBlades: ["MetalBlade"],
};

function formatName(raw) {
  // Already human-readable (e.g. "Bumblebee 3-60GP") — strip the trailing
  // ratchet/bit code (e.g. " 3-60GP") and use the plain product name.
  if (raw.includes(" ")) {
    return raw.replace(/\s+\d+-\d+[A-Za-z]*$/, "").trim();
  }

  return raw
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/([A-Za-z])(\d)/g, "$1 $2")
    .replace(/(\d)([A-Za-z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim();
}

function deriveName(fileBase, category) {
  const prefixes = PREFIXES[category] || [];
  for (const prefix of prefixes) {
    if (fileBase.startsWith(prefix)) {
      return formatName(fileBase.slice(prefix.length));
    }
  }
  return formatName(fileBase);
}

const generations = readdirSync(ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const data = {};

for (const gen of generations) {
  const genDir = join(ROOT, gen);
  const categories = readdirSync(genDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  data[gen] = {};

  for (const category of categories) {
    const catDir = join(genDir, category);
    const files = readdirSync(catDir, { withFileTypes: true })
      .filter((d) => d.isFile())
      .map((d) => d.name)
      .sort();

    data[gen][category] = files.map((file) => {
      const dot = file.lastIndexOf(".");
      const base = dot === -1 ? file : file.slice(0, dot);
      const part = {
        id: `${gen}/${category}/${base}`.toLowerCase(),
        name: deriveName(base, category),
        image: `/beyblade-parts/${gen}/${category}/${file}`,
      };
      // Some Blades come with a ratchet built in (filename prefixed "RatchetBlade") —
      // these don't need a separate Ratchet selection.
      if (category === "Blades" && base.startsWith("RatchetBlade")) {
        part.integratedRatchet = true;
      }
      return part;
    });
  }
}

const header = `// AUTO-GENERATED by scripts/generate-beyblade-parts.mjs — do not edit by hand.\n\nexport interface PartOption {\n  id: string;\n  name: string;\n  image: string;\n  integratedRatchet?: boolean;\n}\n\n`;

const body = `export const beybladeParts = ${JSON.stringify(data, null, 2)} as const satisfies Record<string, Record<string, PartOption[]>>;\n`;

writeFileSync(OUT, header + body);
console.log(`Wrote ${OUT}`);
for (const gen of generations) {
  for (const category of Object.keys(data[gen])) {
    console.log(`${gen}/${category}: ${data[gen][category].length}`);
  }
}
